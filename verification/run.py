"""Run the SlipSurfaceIQ LE verification suite.

Usage (from the repository root)::

    python verification/run.py                 # run every active case
    python verification/run.py --fast          # closed-form cases only
    python verification/run.py --case acads-1a
    python verification/run.py --write         # also update docs/verification.md

The exit status is 1 if any active case falls outside its tolerance.
"""

from __future__ import annotations

import argparse
import datetime as _dt
import json
import math
import platform
import sys
import time
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

import slipsurface  # noqa: E402
from slipsurface.lem import method_name  # noqa: E402

CASES_FILE = ROOT / "verification" / "cases.json"
DOC_FILE = ROOT / "docs" / "verification.md"


@dataclass
class Row:
    case: str
    method: str
    computed: float
    reference: float
    ok: bool
    error: str = ""

    @property
    def diff(self) -> float:
        return self.computed - self.reference


def load_cases(path: Path = CASES_FILE) -> list[dict]:
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)["cases"]


def within(computed: float, reference: float, tol: dict) -> bool:
    if not math.isfinite(computed):
        return False
    limit = max(tol.get("abs", 0.0), tol.get("rel", 0.0) * abs(reference))
    return abs(computed - reference) <= limit


def run_analytic(case: dict) -> list[Row]:
    from verification.analytic import FUNCTIONS

    results = FUNCTIONS[case["function"]](**case.get("kwargs", {}))
    return [
        Row(case["id"], m, fs, ref, within(fs, ref, case["tolerance"]))
        for m, (fs, ref) in results.items()
    ]


def run_project(case: dict) -> list[Row]:
    from slipsurface.analysis import run_analysis
    from slipsurface.project import Project

    project = Project.load(ROOT / case["project"])
    methods = list(case["reference"])
    project.methods.methods = methods
    result = run_analysis(project)
    rows = []
    for m in methods:
        ref = float(case["reference"][m])
        if m in result.results:
            fs = float(result.results[m].fos)
            rows.append(Row(case["id"], m, fs, ref, within(fs, ref, case["tolerance"])))
        else:
            rows.append(Row(case["id"], m, math.nan, ref, False, result.errors.get(m, "no result")))
    return rows


def run_case(case: dict) -> list[Row]:
    if case["kind"] == "analytic":
        return run_analytic(case)
    if case["kind"] == "project":
        return run_project(case)
    raise ValueError(f"{case['id']}: unknown kind {case['kind']!r}")


def _fmt(x: float, digits: int = 4) -> str:
    return f"{x:.{digits}f}" if math.isfinite(x) else "—"


def _fmt_diff(d: float) -> str:
    return f"{d:+.1e}" if abs(d) < 1e-4 else f"{d:+.4f}"


def markdown(cases: list[dict], rows: list[Row], elapsed: float) -> str:
    by_case: dict[str, list[Row]] = {}
    for r in rows:
        by_case.setdefault(r.case, []).append(r)
    n_ok = sum(r.ok for r in rows)
    lines = [
        "# Verification results",
        "",
        "<!-- Generated by `python verification/run.py --write`. Do not edit by hand. -->",
        "",
        f"SlipSurfaceIQ LE {slipsurface.__version__} · "
        f"{_dt.date.today().isoformat()} · Python {platform.python_version()} "
        f"on {platform.system()} · {n_ok}/{len(rows)} checks passed in {elapsed:.0f} s.",
        "",
        "How the cases are defined and how to add one is described in "
        "[`verification/README.md`](../verification/README.md).",
        "",
        "## Results",
        "",
    ]
    for case in cases:
        if case["id"] not in by_case:
            continue
        tol = case["tolerance"]
        tol_txt = ", ".join(f"{k} {v:g}" for k, v in tol.items())
        lines += [
            f"### {case['title']}",
            "",
            f"*{case['reference_type']}* — {case['source']}. Tolerance: {tol_txt}.",
        ]
        if "benchmark_fs" in case:
            lines.append(f"Benchmark (referee) FS = {case['benchmark_fs']:.2f}.")
        if "reference_note" in case:
            lines.append(case["reference_note"] + ".")
        lines += [
            "",
            "| Method | Computed FS | Reference FS | Difference | Result |",
            "|---|---:|---:|---:|:---:|",
        ]
        for r in by_case[case["id"]]:
            lines.append(
                f"| {method_name(r.method)} | {_fmt(r.computed)} | {_fmt(r.reference)} | "
                f"{_fmt_diff(r.diff) if math.isfinite(r.computed) else r.error} | "
                f"{'✅' if r.ok else '❌'} |"
            )
        lines.append("")
    planned = [c for c in cases if c.get("status") == "planned"]
    if planned:
        lines += [
            "## Planned cases",
            "",
            "Contributions are welcome — see `verification/README.md`.",
            "",
            "| Case | Reference |",
            "|---|---|",
        ]
        lines += [f"| {c['title']} | {c['source']} |" for c in planned]
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--case", action="append", help="run only this case id (repeatable)")
    ap.add_argument("--fast", action="store_true", help="closed-form cases only")
    ap.add_argument("--write", action="store_true", help=f"write {DOC_FILE.relative_to(ROOT)}")
    args = ap.parse_args(argv)

    cases = load_cases()
    selected = [c for c in cases if c.get("status") == "active"]
    if args.case:
        unknown = set(args.case) - {c["id"] for c in cases}
        if unknown:
            ap.error(f"unknown case id(s): {', '.join(sorted(unknown))}")
        selected = [c for c in selected if c["id"] in args.case]
    if args.fast:
        selected = [c for c in selected if c["kind"] == "analytic"]

    t0 = time.perf_counter()
    rows: list[Row] = []
    for case in selected:
        t = time.perf_counter()
        case_rows = run_case(case)
        rows += case_rows
        mark = "ok" if all(r.ok for r in case_rows) else "FAIL"
        print(f"[{mark:>4}] {case['id']:<24} {time.perf_counter() - t:6.1f} s")
        for r in case_rows:
            if not r.ok:
                print(
                    f"       {r.method}: computed {_fmt(r.computed)} "
                    f"reference {_fmt(r.reference)} {r.error}"
                )
    elapsed = time.perf_counter() - t0
    failed = [r for r in rows if not r.ok]
    print(f"{len(rows) - len(failed)}/{len(rows)} checks passed in {elapsed:.1f} s")

    if args.write:
        DOC_FILE.parent.mkdir(exist_ok=True)
        DOC_FILE.write_text(markdown(cases, rows, elapsed) + "\n", encoding="utf-8")
        print(f"wrote {DOC_FILE.relative_to(ROOT)}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
